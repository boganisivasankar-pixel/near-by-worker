"""Safely migrate a verified Nearby Worker SQLite backup to an empty PostgreSQL database.

The default mode validates only the SQLite source. It never imports app.py.
Use --check-target for a read-only PostgreSQL emptiness check, and --apply only
after reviewing the source backup and confirming the target is disposable/empty.
"""

import argparse
import hashlib
import json
import os
import sqlite3
import sys
from pathlib import Path
from urllib.parse import urlsplit


